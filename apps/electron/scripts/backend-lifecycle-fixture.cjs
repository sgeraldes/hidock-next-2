// Runs only under Electron with a disposable profile supplied by the test runner.
const { app, BrowserWindow } = require('electron')
const { readFileSync, writeFileSync, existsSync, mkdirSync } = require('node:fs')
const { join, resolve } = require('node:path')
const assert = require('node:assert/strict')
const { spawn } = require('node:child_process')
const root = process.env.HIDOCK_BACKEND_FIXTURE_ROOT
if (!root || !resolve(root).includes('hidock-backend-fixture-')) throw new Error('Disposable fixture root required')
mkdirSync(join(root, 'appdata'), { recursive: true })
app.setPath('appData', join(root, 'appdata'))
process.env.HIDOCK_DEV_USERDATA = join(root, 'profile')
const secondary = process.argv.includes('--fixture-secondary')
if (!secondary) process.argv.push('--backend-only')
if (!secondary && existsSync(join(root, 'result.json'))) process.argv.push('--no-schema-work')
const pause = () => new Promise(resolve => setTimeout(resolve, 100))
async function until(check) {
  const end = Date.now() + 30000
  while (Date.now() < end) { const result = await check(); if (result) return result; await pause() }
  throw new Error('Fixture timed out')
}
require('../out/main/index.js')
if (!secondary) void (async () => {
  const lockPath = join(root, 'profile', 'brain.json')
  const lock = await until(() => { try { return JSON.parse(readFileSync(lockPath, 'utf8')) } catch { return null } })
  const api = async (path, method = 'GET', body, expected = method === 'POST' ? 202 : 200) => {
    const response = await fetch(`http://127.0.0.1:${lock.port}${path}`, { method, body: body === undefined ? undefined : JSON.stringify(body), headers: { Authorization: `Bearer ${lock.token}`, 'Content-Type': 'application/json' } })
    assert.equal(response.status, expected, path)
    return response.json()
  }
  await until(async () => (await api('/backend/status')).servicesReady)
  const schemaWorkDisabled = (await api('/backend/status')).schemaWorkDisabled
  assert.equal(schemaWorkDisabled, existsSync(join(root, 'result.json')))
  assert.equal((await api('/health')).pid, process.pid)
  assert.equal((await api('/backend/status')).uiAttached, false)
  const tray = await until(() => globalThis.__HIDOCK_STARTUP_STATE__?.backendTray)
  assert.equal(tray.tray.isDestroyed(), false)
  assert.ok(tray.tray.getBounds().width > 0, 'native Windows tray icon exists')
  tray.menu.getMenuItemById('pause').click()
  assert.equal(tray.status().paused, true)
  await api('/recordings?since=2026-10-05T03:00:00Z&until=2026-10-06T03:00:00Z&limit=50')
  tray.menu.getMenuItemById('pause').click()
  assert.equal(tray.status().paused, false)
  tray.menu.getMenuItemById('limit-cpuPercent-50').click()
  assert.equal(JSON.parse(readFileSync(join(root, 'profile', 'backend-tray-settings.json'), 'utf8')).limits.cpuPercent, 50)
  await until(() => { tray.refresh(); return tray.status().resources.cpuPercent !== null })
  assert.ok(tray.status().resources.ramMb > 0)
  // Fixture-only seeding of the actual SQLite engine. This connection can
  // never resolve the owner's profile or original audio paths.
  const Sqlite = require('better-sqlite3')
  const db = new Sqlite(join(root, 'storage', 'data', 'hidock.db'))
  for (const [id, personal] of [['selected', 0], ['unrelated', 0], ['excluded', 1], ['cancelable', 0]]) {
    db.prepare(`INSERT OR IGNORE INTO recordings (id, filename, file_path, file_size, date_recorded, duration_seconds, status, location, transcription_status, source, on_local, on_device, is_imported, personal)
      VALUES (?, ?, ?, 1, '2026-10-05T13:00:00.000Z', 30, 'none', 'local-only', 'none', 'import', 1, 0, 1, ?)`).run(id, `${id}.wav`, join(root, 'missing-fixture-audio.wav'), personal)
  }
  db.prepare("INSERT OR IGNORE INTO transcription_queue (id, recording_id, provider, status) VALUES ('unrelated-job', 'unrelated', 'vibevoice', 'pending')").run()
  db.prepare("INSERT OR IGNORE INTO transcription_queue (id, recording_id, provider, status) VALUES ('cancelable-job', 'cancelable', 'vibevoice', 'pending')").run()
  const inventory = await api('/recordings?since=2026-10-05T03:00:00Z&until=2026-10-06T03:00:00Z&limit=50')
  assert.equal(inventory.recordings.some(row => row.id === 'excluded'), false)
  const client = spawn(process.execPath, [resolve(__dirname, 'backend-client.mjs'), lockPath, 'inventory', '2026-10-05T03:00:00Z', '2026-10-06T03:00:00Z'], { env: { ...process.env, ELECTRON_RUN_AS_NODE: '1' }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  let clientOutput = ''
  client.stdout.on('data', chunk => { clientOutput += chunk })
  const clientCode = await new Promise((resolve, reject) => { client.once('error', reject); client.once('exit', resolve) })
  assert.equal(clientCode, 0)
  assert.equal(JSON.parse(clientOutput).recordings.some(row => row.id === 'excluded'), false)
  assert.equal(clientOutput.includes(lock.token), false)
  const submission = { recordingIds: ['selected'], provider: 'vibevoice', requestId: 'fixture-directed-request' }
  const admitted = await api('/transcriptions', 'POST', submission)
  await until(async () => (await api('/transcriptions?ids=selected'))[0].jobs.some(job => job.status === 'failed'))
  const replay = await api('/transcriptions', 'POST', submission)
  assert.equal(replay.replayed, true)
  assert.equal(replay.jobs[0].queueItemId, admitted.jobs[0].queueItemId)
  assert.equal(db.prepare("SELECT count(*) AS n FROM transcription_queue WHERE recording_id = 'selected'").get().n, 1)
  assert.equal(db.prepare("SELECT status FROM transcription_queue WHERE id = 'unrelated-job'").get().status, 'pending')
  assert.equal((await api('/transcriptions?ids=excluded')).length, 0)
  await api('/transcriptions/cancelable/cancel', 'POST')
  assert.equal(db.prepare("SELECT count(*) AS n FROM transcription_queue WHERE recording_id = 'cancelable' AND status IN ('pending', 'processing')").get().n, 0)
  const session = await api('/rag/sessions', 'POST', { title: 'Synthetic backend conversation' }, 201)
  assert.ok(session.id)
  const ragStatus = await api('/rag/status')
  assert.ok(ragStatus.chatPlan.calls.length)
  const invalidChat = await api('/rag/chat', 'POST', { sessionId: session.id, message: '' }, 400)
  assert.ok(invalidChat.error)
  db.close()
  await api('/backend/ui', 'POST')
  const window = await until(() => BrowserWindow.getAllWindows().find(w => !w.isDestroyed()))
  await until(() => !window.webContents.isLoadingMainFrame())
  console.log('[fixture] UI state', { visible: window.isVisible(), loading: window.webContents.isLoading(), url: window.webContents.getURL() })
  assert.equal(window.isVisible(), true)
  assert.equal(window.webContents.getURL().split('#')[0], require('node:url').pathToFileURL(resolve(__dirname, '../out/renderer/index.html')).href)
  const capture = await window.webContents.capturePage()
  assert.equal(capture.isEmpty(), false)
  writeFileSync(join(root, 'rendered-ui.png'), capture.toPNG())
  const firstWindowId = window.id
  window.close()
  await until(async () => !(await api('/backend/status')).uiAttached)
  assert.equal((await api('/health')).pid, process.pid)
  const child = spawn(process.execPath, [__filename, '--fixture-secondary'], { env: process.env, windowsHide: true, stdio: 'ignore' })
  const childExit = new Promise((resolve, reject) => { child.once('error', reject); child.once('exit', code => code === 0 ? resolve() : reject(new Error(`Secondary exit ${code}`))) })
  const reopened = await until(() => BrowserWindow.getAllWindows().find(w => !w.isDestroyed()))
  await until(() => !reopened.webContents.isLoadingMainFrame())
  assert.equal(reopened.isVisible(), true)
  await childExit
  assert.notEqual(reopened.id, firstWindowId)
  assert.equal((await api('/health')).pid, process.pid)
  writeFileSync(join(root, 'result.json'), JSON.stringify({ pid: process.pid, firstWindowId, reopenedWindowId: reopened.id, rendered: true, samePid: true, schemaWorkDisabled, directedFailurePersisted: true, unrelatedQueueUntouched: true, requestReplay: true, exclusionApplied: true, queuedCancellation: true, conversationCreated: true, fixedClientTested: true, profile: app.getPath('userData'), appData: app.getPath('appData'), schemaFileExists: existsSync(join(root, 'storage', 'data', 'hidock.db')) }, null, 2))
  await tray.requestExit('quit')
})().catch(error => { console.error('[fixture]', error); app.exit(1) })
